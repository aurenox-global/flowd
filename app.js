function applyLang(lang) {
  if (!I18N[lang]) lang = "es";
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-t]").forEach(function (el) {
    var k = el.getAttribute("data-t");
    if (I18N[lang][k] != null) el.textContent = I18N[lang][k];
  });
  document.querySelectorAll("[data-t-html]").forEach(function (el) {
    var k = el.getAttribute("data-t-html");
    if (I18N[lang][k] != null) el.innerHTML = I18N[lang][k];
  });
  var t = document.querySelector('meta[name="description"]');
  if (t) t.setAttribute("content", I18N[lang]["meta.desc"]);
  document.title = I18N[lang]["meta.title"];
  document.querySelectorAll("[data-setlang]").forEach(function (b) {
    b.classList.toggle("active", b.getAttribute("data-setlang") === lang);
  });
  try { localStorage.setItem("flowd.lang", lang); } catch (e) {}
}

function applyTheme(theme) {
  if (theme !== "light") theme = "dark";
  document.documentElement.setAttribute("data-theme", theme);
  var meta = document.querySelector('meta[name="theme-color"]');
  if (meta) meta.setAttribute("content", theme === "light" ? "#F6F7F9" : "#0E1013");
  var ic = document.querySelector("[data-theme-toggle] .material-icons");
  if (ic) ic.textContent = theme === "light" ? "dark_mode" : "light_mode";
  try { localStorage.setItem("flowd.theme", theme); } catch (e) {}
}

(function init() {
  var lang = "es";
  try { lang = localStorage.getItem("flowd.lang") || "es"; } catch (e) {}
  applyLang(lang);

  var theme = "dark";
  try { theme = localStorage.getItem("flowd.theme") || "dark"; } catch (e) {}
  applyTheme(theme);

  document.querySelectorAll("[data-setlang]").forEach(function (b) {
    b.addEventListener("click", function () { applyLang(b.getAttribute("data-setlang")); });
  });
  var tt = document.querySelector("[data-theme-toggle]");
  if (tt) tt.addEventListener("click", function () {
    var cur = document.documentElement.getAttribute("data-theme");
    applyTheme(cur === "light" ? "dark" : "light");
  });
})();
